import assert from 'node:assert/strict';
import { createJourneyProgress } from '../src/journeyProgress.js';
const values = new Map();
const storage = { getItem: (k) => values.get(k) ?? null, setItem: (k,v) => values.set(k,v), removeItem: (k) => values.delete(k) };
let clock = 1000;
const journey = createJourneyProgress({experienceId: 'ciudad-A', storage, now: () => clock});
assert.deepEqual(journey.read('lugar-1'), {discoveredAt:null, arrivedAt:null, completedAt:null});
journey.record('lugar-1','discovered');
clock = 2000;
journey.record('lugar-1','discovered');
assert.equal(journey.read('lugar-1').discoveredAt, 1000);
journey.record('lugar-1','arrived');
clock = 3000;
journey.record('lugar-1','completed');
assert.deepEqual(journey.read('lugar-1'), {discoveredAt:1000, arrivedAt:2000, completedAt:3000});
assert.equal(createJourneyProgress({experienceId: 'ciudad-A',storage}).read('lugar-1').completedAt, 3000);
assert.equal(createJourneyProgress({experienceId: 'ciudad-B',storage}).read('lugar-1').completedAt, null);
assert.equal(journey.read('lugar-2').arrivedAt, null);
journey.record('lugar-2', 'completed');
assert.equal(journey.read('lugar-2').arrivedAt, journey.read('lugar-2').completedAt);
journey.clear('lugar-1');
assert.equal(journey.read('lugar-1').completedAt, null);
const broken = createJourneyProgress({storage: {getItem(){throw Error('blocked')},setItem(){throw Error('blocked')},removeItem(){throw Error('blocked')}}, now: () => 4500});
broken.record('one', 'arrived');
assert.equal(broken.read('one').arrivedAt, 4500);
assert.equal(journey.record('', 'arrived'), null);
console.log('OK: progreso local, persistencia, aislamiento y degradación segura');
